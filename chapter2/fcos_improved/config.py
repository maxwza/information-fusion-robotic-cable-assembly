# ============================================================
# Configuration Validation
# ============================================================

def validate_config():
    """
    检查关键配置是否一致。
    """

    # --------------------------------------------------------
    # Dataset
    # --------------------------------------------------------

    assert DATASET["num_classes"] == len(
        DATASET["class_names"]
    ), (
        "num_classes does not match "
        "class_names."
    )

    # --------------------------------------------------------
    # Backbone
    # --------------------------------------------------------

    assert len(
        BACKBONE["depths"]
    ) == 4

    assert len(
        BACKBONE["dims"]
    ) == 4

    assert len(
        BACKBONE["out_indices"]
    ) == 4

    # --------------------------------------------------------
    # EMA
    # --------------------------------------------------------

    assert set(
        EMA["apply_to"]
    ).issubset(
        {
            "C2",
            "C3",
            "C4",
            "C5"
        }
    )

    # --------------------------------------------------------
    # 当前论文方法：
    # EMA 只使用 C4 和 C5
    # --------------------------------------------------------

    assert EMA["apply_to"] == [
        "C4",
        "C5"
    ], (
        "For the current Chapter 2 design, "
        "EMA should be applied to C4 and C5."
    )

    # --------------------------------------------------------
    # FPN
    # --------------------------------------------------------

    assert len(
        SIMAM_FPN["in_channels"]
    ) == 4

    assert SIMAM_FPN["num_levels"] == 4

    # --------------------------------------------------------
    # PFNM
    # --------------------------------------------------------

    assert PFNM["num_levels"] == 4

    # --------------------------------------------------------
    # FCOS
    # --------------------------------------------------------

    assert FCOS["num_classes"] == DATASET[
        "num_classes"
    ]

    assert len(
        FCOS["strides"]
    ) == 4

    # --------------------------------------------------------
    # Input size
    # --------------------------------------------------------

    assert DATASET["image_size"] == INFERENCE[
        "image_size"
    ]

    # --------------------------------------------------------
    # Split
    # --------------------------------------------------------

    split_sum = (
        DATASET["train_ratio"]
        + DATASET["val_ratio"]
        + DATASET["test_ratio"]
    )

    assert abs(
        split_sum - 1.0
    ) < 1e-6, (
        "Dataset split ratios must sum to 1."
    )

    return True


